
CREATE TABLE customer (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR NOT NULL UNIQUE,
    password_hash VARCHAR NOT NULL,
    full_name VARCHAR NOT NULL,
    date_of_birth DATE NOT NULL,
    phone VARCHAR,
    status VARCHAR NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_customer_date_of_birth
        CHECK (date_of_birth <= CURRENT_DATE)
);

CREATE INDEX idx_customer_status
    ON customer(status);

    -- ============================================
-- Section 2: Insurance Product
-- ============================================

CREATE TABLE insurance_product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR NOT NULL UNIQUE,
    policy_name VARCHAR NOT NULL,
    policy_type VARCHAR NOT NULL,
    term_months INTEGER NOT NULL,
    premium_frequency VARCHAR NOT NULL,
    premium_amount NUMERIC(19,2) NOT NULL,
    sum_insured NUMERIC(19,2) NOT NULL,
    min_entry_age INTEGER NOT NULL,
    max_entry_age INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_product_premium_amount
        CHECK (premium_amount > 0),

    CONSTRAINT chk_product_sum_insured
        CHECK (sum_insured > 0)
);

CREATE INDEX idx_insurance_product_active
    ON insurance_product(active);

    -- ============================================
-- Section 3: Customer Policy
-- ============================================

CREATE TABLE customer_policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number VARCHAR NOT NULL UNIQUE,

    customer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    start_date DATE NOT NULL,
    maturity_date DATE NOT NULL,

    premium_frequency VARCHAR NOT NULL,
    premium_amount NUMERIC(19,2) NOT NULL,
    sum_insured NUMERIC(19,2) NOT NULL,
    total_premium_payable NUMERIC(19,2) NOT NULL,

    status VARCHAR NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_customer_policy_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id),

    CONSTRAINT fk_customer_policy_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_product(product_id),

    CONSTRAINT uq_customer_policy_customer_product
        UNIQUE (customer_id, product_id)
);

CREATE INDEX idx_customer_policy_customer
    ON customer_policy(customer_id);

CREATE INDEX idx_customer_policy_status
    ON customer_policy(status);


    -- ============================================
-- Section 4: Premium Installment
-- ============================================

CREATE TABLE premium_installment (
    installment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    policy_id BIGINT NOT NULL,
    installment_number INTEGER NOT NULL,

    due_date DATE NOT NULL,
    grace_period_end_date DATE NOT NULL,

    scheduled_amount NUMERIC(19,2) NOT NULL,
    paid_amount NUMERIC(19,2) NOT NULL DEFAULT 0.00,

    payment_status VARCHAR NOT NULL,

    CONSTRAINT fk_installment_policy
        FOREIGN KEY (policy_id)
        REFERENCES customer_policy(policy_id),

    CONSTRAINT uq_policy_installment_number
        UNIQUE (policy_id, installment_number),

    CONSTRAINT chk_installment_paid_amount
        CHECK (
            paid_amount >= 0
            AND paid_amount <= scheduled_amount
        )
);

-- ============================================
-- Section 5: Premium Payment
-- ============================================

CREATE TABLE premium_payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    installment_id BIGINT NOT NULL,
    transaction_reference VARCHAR NOT NULL UNIQUE,

    payment_date TIMESTAMP WITH TIME ZONE NOT NULL,
    amount_paid NUMERIC(19,2) NOT NULL,
    penalty_amount NUMERIC(19,2) NOT NULL DEFAULT 0.00,
    payment_method VARCHAR NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payment_installment
        FOREIGN KEY (installment_id)
        REFERENCES premium_installment(installment_id),

    CONSTRAINT chk_payment_amount
        CHECK (amount_paid > 0)
);

CREATE INDEX idx_premium_payment_installment
    ON premium_payment(installment_id);

CREATE INDEX idx_premium_payment_date
    ON premium_payment(payment_date);

    -- ============================================
-- Section 6: AI Recommendation Request
-- ============================================

CREATE TABLE ai_recommendation_request (
    recommendation_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL,

    insurance_goals TEXT,
    preferred_term VARCHAR,
    preferred_policy_type VARCHAR,
    calculated_age INTEGER,

    model_name VARCHAR NOT NULL,
    model_version VARCHAR,
    prompt_version VARCHAR,

    requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_recommendation_request_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id)
);

CREATE INDEX idx_recommendation_request_customer
    ON ai_recommendation_request(customer_id);

CREATE INDEX idx_recommendation_request_date
    ON ai_recommendation_request(requested_at);

    -- ============================================
-- Section 7: AI Recommendation Item
-- ============================================

CREATE TABLE ai_recommendation_item (
    recommendation_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    recommendation_request_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    rank_order INTEGER NOT NULL,
    recommendation_reason TEXT,
    suitability VARCHAR,
    selected_for_registration BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_recommendation_item_request
        FOREIGN KEY (recommendation_request_id)
        REFERENCES ai_recommendation_request(recommendation_request_id),

    CONSTRAINT fk_recommendation_item_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_product(product_id),

    CONSTRAINT uq_recommendation_request_product
        UNIQUE (recommendation_request_id, product_id)
);

-- ============================================
-- Additional integrity constraints
-- ============================================

ALTER TABLE premium_installment
    ADD CONSTRAINT chk_installment_scheduled_amount
    CHECK (scheduled_amount > 0);

ALTER TABLE premium_payment
    ADD CONSTRAINT chk_payment_penalty_amount
    CHECK (penalty_amount >= 0);

ALTER TABLE customer_policy
    ADD CONSTRAINT chk_policy_premium_amount
    CHECK (premium_amount > 0);

ALTER TABLE customer_policy
    ADD CONSTRAINT chk_policy_sum_insured
    CHECK (sum_insured > 0);

ALTER TABLE customer_policy
    ADD CONSTRAINT chk_policy_total_premium
    CHECK (total_premium_payable > 0);

ALTER TABLE insurance_product
    ADD CONSTRAINT chk_product_term
    CHECK (term_months > 0);

ALTER TABLE insurance_product
    ADD CONSTRAINT chk_product_entry_age
    CHECK (min_entry_age >= 0 AND max_entry_age >= min_entry_age);